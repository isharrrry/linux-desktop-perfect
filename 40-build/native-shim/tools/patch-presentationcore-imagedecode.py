#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""PC 补丁 R：图像解码失败降级（ImageSourceConverter / BitmapSource / CachedBitmap）。

【为什么必须有这个补丁】
K-1424 实测：把自产 PresentationCore.dll 替换到共享框架后启动即崩：

    XamlParseException: 'Provide value on 'System.Windows.Baml2006.TypeConverterMarkupExtension' threw an exception.'
      ---> NotImplementedException
       at MS.Internal.HRESULT.Check(Int32 hr)
       at System.Windows.Media.Imaging.BitmapDecoder.SetupDecoderFromUriOrStream(...)
       at System.Windows.Media.Imaging.BitmapFrame.CreateFromUriOrStream(...)
       at System.Windows.Media.ImageSourceConverter.ConvertFrom(...)

根因不是「缺解码器」，而是**解码失败后的恢复路径也依赖 MilCore 的 WIC 桥**：
`RecoverFromDecodeFailure` 调 `Create(1,1,...)` → `CachedBitmap.InitFromMemoryPtr` →
`WICImagingFactory.CreateBitmapFromMemory` → `HRESULT.E_NOTIMPL`（Linux 上未实现）。
于是「失败 → 再失败」把 XAML 解析整个带崩。

现装件（K-1405：来源不可考、比源码新）在这 3 处做了适配：URI 分支吞异常返 null、
两个恢复方法体清空 ⇒ 解码失败时**不显示**而不是崩。本补丁把这 3 处搬进源码，
使「自产件替换共享框架」不再需要 Cecil 后处理（K-1424 当时是 /tmp 临时后处理，重编译会回退）。

【生成物】3 个 .Linux.cs（上游逐字 + 定点替换 + 文件头横幅）：
  ImageSourceConverter.Linux.cs  ← System/Windows/Media/ImageSourceConverter.cs
  BitmapSource.Linux.cs          ← System/Windows/Media/Imaging/BitmapSource.cs
  CachedBitmap.Linux.cs          ← System/Windows/Media/Imaging/CachedBitmap.cs
并在 PresentationCore.Linux.csproj 里接线（Compile Remove 上游 + Include 生成物）。

【边界】只做「解码失败降级」，不改解码成功路径；`RecoverFromDecodeFailure` 仍抛
`OnDecodeFailed` 事件（上层可换失败图），只是不再尝试造 1×1 占位图。
"""

import argparse
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "../..", ".."))
PC_UP = os.path.join(ROOT, "40-build/upstream/wpf/src/Microsoft.DotNet.Wpf/src/PresentationCore")
PC_LINUX = os.path.join(ROOT, "40-build/wpf-port/src/Microsoft.DotNet.Wpf.Linux/src/PresentationCore")
CSPROJ = os.path.join(PC_LINUX, "PresentationCore.Linux.csproj")

MARKER_BEGIN = "  <!-- ==== T2 · 补丁 R：图像解码失败降级 BEGIN ==== -->"
MARKER_END = "  <!-- ==== T2 · 补丁 R：图像解码失败降级 END ==== -->"

JOBS = [
    {
        "src_rel": "System/Windows/Media/ImageSourceConverter.cs",
        "out": "ImageSourceConverter.Linux.cs",
        "why": "URI 分支：解码失败返回 null，不让异常终止 XAML 解析",
    },
    {
        "src_rel": "System/Windows/Media/Imaging/BitmapSource.cs",
        "out": "BitmapSource.Linux.cs",
        "why": "RecoverFromDecodeFailure：不再造 1×1 占位图（MilCore 桥未实现）",
    },
    {
        "src_rel": "System/Windows/Media/Imaging/CachedBitmap.cs",
        "out": "CachedBitmap.Linux.cs",
        "why": "InitFromMemoryPtr：unmanaged bitmap 封装依赖 MilCore WIC 桥，短路",
    },
]

BANNER = """// <auto-generated>
// WPF-Linux 补丁 R（图像解码失败降级）：本文件由
//   40-build/native-shim/tools/patch-presentationcore-imagedecode.py
// 从上游 {src_rel} 生成（上游逐字 + {n} 处定点替换）。
// 不要手改：改上游或改生成脚本，再重跑脚本。
// 原因：K-1424 —— 解码失败后的恢复路径依赖 MilCore 的 WIC 桥，Linux 上抛 E_NOTIMPL，
//       会把 XAML 解析整个带崩；这里降级为「不显示」而不是「崩溃」。
// </auto-generated>
"""


def read(p):
    with open(p, "r", encoding="utf-8") as f:
        return f.read()


def replace_once(src, old, new, what):
    n = src.count(old)
    if n != 1:
        print(f"[失败] 锚点出现 {n} 次（要求 1）：{what}")
        sys.exit(1)
    return src.replace(old, new, 1)


def method_body_span(src, signature_marker):
    """返回 (body_start, body_end) —— signature_marker 之后的第一个 '{' 与其匹配的 '}' 之间。"""
    i = src.find(signature_marker)
    if i < 0:
        print(f"[失败] 找不到方法签名：{signature_marker}")
        sys.exit(1)
    b = src.find("{", i + len(signature_marker))
    if b < 0:
        print(f"[失败] 找不到方法体起始：{signature_marker}")
        sys.exit(1)
    depth = 0
    k = b
    while k < len(src):
        ch = src[k]
        if ch == "{":
            depth += 1
        elif ch == "}":
            depth -= 1
            if depth == 0:
                return b, k
        k += 1
    print(f"[失败] 方法体大括号不平衡：{signature_marker}")
    sys.exit(1)


def patch_image_source_converter(src):
    old = """                    return BitmapFrame.CreateFromUriOrStream(
                        uriHolder.BaseUri,
                        uriHolder.OriginalUri,
                        null,
                        BitmapCreateOptions.None,
                        BitmapCacheOption.Default,
                        null
                        );"""
    new = """                    // WPF-Linux（补丁 R）：Linux 上 CreateFromUriOrStream 走 pack:// 的 stream 桥，
                    //   最终在 HRESULT 检查处抛 E_NOTIMPL；这里降级为「返回 null（图片不显示）」，
                    //   避免 XamlParseException 终止整个窗口构建。
                    try
                    {
                        return BitmapFrame.CreateFromUriOrStream(
                            uriHolder.BaseUri,
                            uriHolder.OriginalUri,
                            null,
                            BitmapCreateOptions.None,
                            BitmapCacheOption.Default,
                            null
                            );
                    }
                    catch (Exception)
                    {
                        return null;
                    }"""
    return replace_once(src, old, new, "ImageSourceConverter.ConvertFrom URI 分支"), 1


def patch_bitmap_source(src):
    marker = "internal void RecoverFromDecodeFailure(Exception e)"
    b, e = method_body_span(src, marker)
    body = src[b + 1:e]
    if "OnDecodeFailed" not in body:
        print("[失败] RecoverFromDecodeFailure 方法体不含 OnDecodeFailed，拒绝改")
        sys.exit(1)
    new_body = """
            // WPF-Linux（补丁 R）：原实现先 Create(1,1,...) 造空图恢复，该路径落到
            //   CachedBitmap.InitFromMemoryPtr → WICImagingFactory.CreateBitmapFromMemory
            //   → HRESULT.E_NOTIMPL（Linux 未实现）。这里跳过占位图，只把失败事件抛给上层
            //   （与现装件行为一致：解码失败时不显示，而不是崩）。
            OnDecodeFailed(this, new ExceptionEventArgs(e));
        """
    return src[:b + 1] + new_body + src[e:], 1


def patch_cached_bitmap(src):
    marker = """private void InitFromMemoryPtr(
                    int pixelWidth,"""
    b, e = method_body_span(src, marker)
    body = src[b + 1:e]
    if "CreateBitmapFromMemory" not in body:
        print("[失败] InitFromMemoryPtr 方法体不含 CreateBitmapFromMemory，拒绝改")
        sys.exit(1)
    new_body = """
            // WPF-Linux（补丁 R）：原实现用 WICImagingFactory.CreateBitmapFromMemory 造
            //   unmanaged bitmap 封装，该 P/Invoke 在 Linux 上抛 E_NOTIMPL。这里短路：
            //   不建立 WIC 句柄（WicSourceHandle 保持 null），调用方在解码失败时会走
            //   BitmapSource.RecoverFromDecodeFailure 的降级路径（补丁 R 已改为只抛事件）。
            _ = pixelWidth; _ = pixelHeight; _ = dpiX; _ = dpiY;
            _ = pixelFormat; _ = palette; _ = buffer; _ = bufferSize; _ = stride;
        """
    return src[:b + 1] + new_body + src[e:], 1


PATCHERS = {
    "ImageSourceConverter.Linux.cs": patch_image_source_converter,
    "BitmapSource.Linux.cs": patch_bitmap_source,
    "CachedBitmap.Linux.cs": patch_cached_bitmap,
}


def main():
    ap = argparse.ArgumentParser(description="PC 补丁 R：图像解码失败降级（生成物 + csproj 接线）")
    ap.add_argument("--check", action="store_true", help="只检查生成物是否与上游同步，不写文件")
    args = ap.parse_args()
    check_only = args.check

    ok = True
    for job in JOBS:
        src_path = os.path.join(PC_UP, job["src_rel"])
        if not os.path.exists(src_path):
            print(f"[失败] 上游不存在：{os.path.relpath(src_path, ROOT)}")
            return 1
        src = read(src_path)
        patched, n = PATCHERS[job["out"]](src)
        banner = BANNER.format(src_rel=job["src_rel"], n=n)
        out = banner + patched
        out_path = os.path.join(PC_LINUX, job["out"])
        up_to_date = os.path.exists(out_path) and read(out_path) == out
        if check_only:
            print(f"[检查] {job['out']}：{'已是最新' if up_to_date else '缺失/与上游不同步'}")
            ok = ok and up_to_date
        elif up_to_date:
            print(f"[生成] {job['out']}：内容已是最新（未重写）")
        else:
            with open(out_path, "w", encoding="utf-8") as f:
                f.write(out)
            print(f"[生成] {job['out']}：已从上游重生成（{n} 处替换）— {job['why']}")

    # ---- csproj 接线 ----
    with open(CSPROJ, encoding="utf-8-sig") as f:
        csproj = f.read()
    if MARKER_BEGIN in csproj:
        print("[接线] csproj 已就位（幂等，不改）")
        return 0 if ok else 1
    if check_only:
        print("[接线] csproj **未接线** —— 需要运行一次不带 --check 的本脚本")
        return 1

    anchor = '  <Import Project="Sdk.targets" Sdk="Microsoft.NET.Sdk" />'
    if csproj.count(anchor) != 1:
        print(f"[失败] csproj 里 Sdk.targets 锚点出现 {csproj.count(anchor)} 次（要求 1）")
        return 1
    lines = [MARKER_BEGIN,
             "  <!-- T2 · 补丁 R：图像解码失败降级（K-1424）—— 解码失败后的恢复路径依赖 MilCore",
             "       的 WIC 桥，Linux 上抛 E_NOTIMPL 会把 XAML 解析带崩 ⇒ 降级为「不显示」。",
             "       生成物 = 上游逐字 + 定点替换（见 tools/patch-presentationcore-imagedecode.py）。 -->",
             "  <ItemGroup>"]
    for job in JOBS:
        lines.append(f'    <Compile Remove="$(UpstreamWpfRoot)src/Microsoft.DotNet.Wpf/src/PresentationCore/{job["src_rel"]}" />')
        lines.append(f'    <Compile Include="$(WpfLinuxRoot)src/Microsoft.DotNet.Wpf.Linux/src/PresentationCore/{job["out"]}" />')
    lines.append("  </ItemGroup>")
    lines.append(MARKER_END)
    block = "\n".join(lines) + "\n"
    csproj = csproj.replace(anchor, block + anchor, 1)
    with open(CSPROJ, "w", encoding="utf-8") as f:
        f.write(csproj)
    print(f"[接线] 已注入 6 行到 {os.path.relpath(CSPROJ, ROOT)}")
    print("\n下一步：node 40-build/wpf-port/build-port.mjs --only PresentationCore")
    return 0


if __name__ == "__main__":
    sys.exit(main())
